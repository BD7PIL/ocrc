/**
 * Password auth for the ssh processes we spawn (plan A1).
 *
 * Why this exists: a peer whose account has no key we can hold (a fresh
 * enterprise VM, a machine whose admin only hands out a password) used to be
 * unreachable — every ssh we spawn carries `BatchMode=yes`, which turns a
 * password prompt into an immediate "Permission denied". The panel offers both
 * modes now, and this module is the password half: **ssh has no flag for a
 * password**, so the only supported route is `SSH_ASKPASS` + a helper program
 * ssh can exec without a terminal.
 *
 * Two properties are load-bearing:
 *   · **The helper contains no secret.** It prints the value of
 *     `OPENCHAMBER_SSH_ASKPASS_VALUE`, which we pass in the child's environment.
 *     A helper with the password baked in would sit on disk readable by anything
 *     that can read the directory, and every regeneration would rewrite it.
 *   · **The helper is not a general prompt answerer.** It answers only prompts
 *     that look like a password or a passphrase, so a host-key `yes/no` question
 *     cannot be answered with a password, and an unexpected prompt prints an
 *     empty line — ssh fails loudly instead of the host proxy hanging for its
 *     whole 20 s budget.
 *
 * Windows needs the two-file dance: ssh on Windows execs `SSH_ASKPASS` through
 * cmd.exe semantics, so the value is a `.cmd` wrapper around a `.ps1` that
 * prints the environment variable. No sshpass anywhere (it is not shipped on
 * Windows, and pulling a C helper into the control side is not worth it).
 */
import { chmodSync, mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { ocrcHome } from '../utils/paths.js'

/** The env var the helper reads. Same name upstream uses — one less thing to
 *  explain when someone compares the two implementations. */
export const ASKPASS_VALUE_ENV = 'OPENCHAMBER_SSH_ASKPASS_VALUE'

export type SshAuthMode = 'key' | 'password'

/** Anything carrying an ssh auth choice: `RemoteInstance` and `RemoteHost` both
 *  are. Absent `sshAuth` means `key` — the behaviour every existing record and
 *  every existing caller had. */
export interface SshAuthSpec {
  sshAuth?: SshAuthMode
  sshPassword?: string
}

/** A password mode without a password is a configuration error, not "key mode". */
export function needsAskpass(spec: SshAuthSpec): boolean {
  return spec.sshAuth === 'password' && !!spec.sshPassword
}

/**
 * The helper script. Reads the value from the environment, and answers only the
 * prompts ssh actually asks a password for:
 *   · `user@host's password:` / `Password:` / `Password for …` → the password;
 *   · `Enter passphrase for key …` → the password too (we disabled pubkey in
 *     this mode, so this only appears if the peer's server-side key setup
 *     differs from what we assumed — answering it is better than failing with a
 *     prompt nobody can see);
 *   · anything else → an empty line, i.e. "no answer": ssh gives up on its own
 *     terms rather than us inventing a reply.
 * No `osascript` fallback on purpose: the control side here is a headless
 * service (the extension host), so a GUI dialog would block forever.
 */
export function askpassShellScript(): string {
  return [
    '#!/bin/sh',
    '# Generated by ocrc. Contains no secret: the password arrives in',
    `# ${ASKPASS_VALUE_ENV} (see src/core/ssh-askpass.ts).`,
    'prompt="$1"',
    'case "$prompt" in',
    `  *assword*|*assphrase*) printf '%s\\n' "$${ASKPASS_VALUE_ENV}"; exit 0 ;;`,
    'esac',
    "printf '\\n'",
    '',
  ].join('\n')
}

/** PowerShell half of the Windows helper: print the variable, nothing else. */
export function askpassPowerShellScript(): string {
  return [
    `$value = [Environment]::GetEnvironmentVariable('${ASKPASS_VALUE_ENV}')`,
    'if ($null -ne $value) { [Console]::Out.WriteLine($value) }',
    '',
  ].join('\n')
}

/** cmd.exe half: ssh execs this path, so it must be a program cmd can run. */
export function askpassCmdWrapper(): string {
  return [
    '@echo off\r',
    '"%SystemRoot%\\System32\\WindowsPowerShell\\v1.0\\powershell.exe"'
      + ' -NoLogo -NoProfile -NonInteractive -ExecutionPolicy Bypass'
      + ' -File "%~dp0askpass.ps1"\r',
    '',
  ].join('\n')
}

/** Where the helpers live. Under our own home, never in a temp dir: the path
 *  ends up in an ssh argv we log, and a per-run temp path would make the log
 *  unreadable and the file unreviewable. */
export function askpassDir(home = ocrcHome()): string {
  return join(home, 'ssh')
}

const written = new Set<string>()

/**
 * Write the helper(s) once per directory and return the path ssh should exec.
 * Idempotent: the content carries no secret, so rewriting is harmless, but the
 * memo keeps a per-command spawn from doing file IO on every probe.
 */
export function ensureAskpassFiles(dir = askpassDir(), platform: NodeJS.Platform = process.platform): string {
  const wrapper = platform === 'win32' ? join(dir, 'askpass.cmd') : join(dir, 'askpass.sh')
  if (written.has(wrapper)) return wrapper
  mkdirSync(dir, { recursive: true, mode: 0o700 })
  if (platform === 'win32') {
    writeFileSync(join(dir, 'askpass.ps1'), askpassPowerShellScript())
    writeFileSync(wrapper, askpassCmdWrapper())
  } else {
    writeFileSync(wrapper, askpassShellScript(), { mode: 0o700 })
    // writeFileSync's mode is masked by umask; the helper is only useful to us,
    // so make 0700 unconditional.
    chmodSync(wrapper, 0o700)
  }
  written.add(wrapper)
  return wrapper
}

/** Test seam: forget the memo so a temp dir is written again. */
export function resetAskpassCache(): void {
  written.clear()
}

/**
 * The environment for one ssh spawn. `undefined` means "inherit ours" — which is
 * exactly right for key mode (the agent socket and `~/.ssh/config` keep working).
 *
 * `SSH_ASKPASS_REQUIRE=force` is what makes ssh use the helper with no tty at
 * all; `DISPLAY` is the older trigger ssh still checks on some builds. Both are
 * set because a missing one shows up as "Permission denied (publickey,password)"
 * — indistinguishable from a wrong password.
 */
export function askpassEnv(
  spec: SshAuthSpec,
  opts: { dir?: string; platform?: NodeJS.Platform } = {},
): NodeJS.ProcessEnv | undefined {
  if (!needsAskpass(spec)) return undefined
  const helper = ensureAskpassFiles(opts.dir ?? askpassDir(), opts.platform)
  return {
    ...process.env,
    SSH_ASKPASS_REQUIRE: 'force',
    SSH_ASKPASS: helper,
    DISPLAY: '1',
    [ASKPASS_VALUE_ENV]: String(spec.sshPassword).trim(),
  }
}

/**
 * The env for a spawn, or `undefined` when ssh should inherit ours. Kept as a
 * separate name because the spawn sites read better as `env: sshSpawnEnv(x)`
 * than as a conditional at each call.
 */
export function sshSpawnEnv(spec: SshAuthSpec, opts: { dir?: string; platform?: NodeJS.Platform } = {}): NodeJS.ProcessEnv | undefined {
  return askpassEnv(spec, opts)
}
